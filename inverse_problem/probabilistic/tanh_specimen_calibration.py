"""
Full-Bayesian calibration: an embedded-model-error linear law vs. tanh data.

The data is generated by a nonlinear law
    F(delta) = A*sigma_y*tanh(delta/(L*eps_ref)) + N(0, sigma_N^2)
Over eps in [0, 0.2%] a straight line sigma = E*eps cannot fit it. Instead of an
external discrepancy term, the model parameter itself is made uncertain,
    E ~ LogNormal  with  E[E] = mu_E,  SD[E] = sigma_E   (moments in MPa),
and we infer its moments theta = (mu_E, sigma_E). A modulus is positive and its
uncertainty is right-skewed, hence lognormal rather than normal. The model
response sigma_i = E * eps_i is then lognormal too (E scaled by a constant).

The likelihood is the *independent-normal approximation*: match the first two moments of the pushed-
forward model output plus the *known* observation noise s_i = sigma_N,i / A_i and
evaluate a Gaussian, with no integral,

    sigma_obs,i | theta ~approx N( mu_E * eps_i,  sigma_E^2 * eps_i^2 + s_i^2 )

Since sigma_i = E * eps_i is a pure scaling, mean = mu_E * eps_i and
var = sigma_E^2 * eps_i^2 are the *exact* first two moments of the lognormal
model output -- only E[E] and Var[E] enter -- so this formula is identical in
form to the normal-E case. The Gaussian likelihood does not resolve the skew of
the true lognormal response; that is the approximation being made.

s_i is fixed to its known value (folded into `svar` by load_data), not inferred.

This script *only* samples the posterior p(theta | data) with emcee and writes
the chain to disk in emcee's native format (an HDF5 HDFBackend). Priors and
sampler settings come from the config JSON; the dataset comes from the
pre-processed observation CSVs written by process_observed_data.py. Summaries /
metrics / plots live in tanh_specimen_postprocess.py.

Run with the `embedded_bias_inference` conda env.
"""

import argparse
import os
import sys

import numpy as np
from scipy.stats import halfnorm, lognorm, norm

import emcee

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(SCRIPT_DIR))
sys.path.insert(0, os.path.join(ROOT, "common"))
from tanh_specimen_common import load_config, load_data  # noqa: E402

DEFAULT_CONFIG = os.path.join(SCRIPT_DIR, "tanh_specimen_calibration_config.json")
DEFAULT_DATA_DIR = os.path.join(
    ROOT, "data_processing", "output"
)  # pre-processed observations
DEFAULT_META_DIR = os.path.join(ROOT, "data", "output")  # DGP metadata (single copy)
DEFAULT_POSTERIOR_DIR = os.path.join(SCRIPT_DIR, "output")
POSTERIOR_FILE = "tanh_specimen_posterior.h5"


# -- prior construction -----------------------------------------------------
def _normal_from_moments(m):
    return norm(loc=m["mean"], scale=m["std"])


def _halfnormal_from_moments(m):
    return halfnorm(scale=m["std"])


def _lognormal_from_moments(m):
    # mean / std are the moments of the *underlying* normal:
    # X ~ LogNormal  <=>  log X ~ N(mean, std^2)
    return lognorm(s=m["std"], scale=np.exp(m["mean"]))


PRIOR_BUILDERS = {
    "normal": _normal_from_moments,
    "halfnormal": _halfnormal_from_moments,
    "lognormal": _lognormal_from_moments,
}


def build_prior_dist(spec):
    """Frozen scipy distribution for one parameter spec from the config."""
    return PRIOR_BUILDERS[spec["prior"]](spec["moments"])


def make_log_prior(param_specs):
    """Return a log_prior(theta) closure driven by the config parameter specs."""
    dists = [build_prior_dist(s) for s in param_specs]
    positive_idx = [i for i, s in enumerate(param_specs) if s.get("positive")]

    def log_prior(theta):
        for i in positive_idx:
            if theta[i] <= 0.0:
                return -np.inf
        return float(sum(d.logpdf(v) for d, v in zip(dists, theta)))

    return log_prior


# -- likelihood / posterior ------------------------------------------------
def log_likelihood(theta, eps, sigma_obs, svar):
    # Independent-normal approximation, Sargsyan et al. 2019 Eq. 13: `mean` and
    # `var` are the exact first two moments of the lognormal model output E*eps
    # (E[E] = mu_E, Var[E] = sigma_E^2) plus the known obs-noise variance `svar`.
    mu_E, sigma_E = theta
    mean = mu_E * eps
    var = sigma_E**2 * eps**2 + svar
    return float(np.sum(norm.logpdf(sigma_obs, mean, np.sqrt(var))))


def make_log_posterior(log_prior):
    def log_posterior(theta, eps, sigma_obs, svar):
        lp = log_prior(theta)
        if not np.isfinite(lp):
            return -np.inf
        return lp + log_likelihood(theta, eps, sigma_obs, svar)

    return log_posterior


# -- sampling -------------------------------------------------------------
def run_sampler(cfg, log_prob_fn, eps, sigma_obs, svar, backend_path):
    specs = cfg["parameters"]
    ndim = len(specs)
    s = cfg["sampler"]
    nwalkers = s["nwalkers"]
    rng = np.random.default_rng(s["seed"])

    # Initialise each walker with an independent draw from the prior.
    dists = [build_prior_dist(spec) for spec in specs]
    p0 = np.column_stack([d.rvs(size=nwalkers, random_state=rng) for d in dists])
    for i, spec in enumerate(specs):
        if spec.get("positive"):
            p0[:, i] = np.abs(p0[:, i])

    backend = emcee.backends.HDFBackend(backend_path)
    backend.reset(nwalkers, ndim)  # always resample

    sampler = emcee.EnsembleSampler(
        nwalkers, ndim, log_prob_fn, args=(eps, sigma_obs, svar), backend=backend
    )
    sampler.run_mcmc(p0, s["nsteps"], progress=True)

    return sampler


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default=DEFAULT_CONFIG)
    parser.add_argument("--data-dir", default=DEFAULT_DATA_DIR)
    parser.add_argument("--meta-dir", default=DEFAULT_META_DIR)
    parser.add_argument("--posterior-dir", default=DEFAULT_POSTERIOR_DIR)
    args = parser.parse_args()

    os.makedirs(args.posterior_dir, exist_ok=True)

    cfg = load_config(args.config)
    data = load_data(args.data_dir, args.meta_dir)

    log_prior = make_log_prior(cfg["parameters"])
    log_posterior = make_log_posterior(log_prior)

    backend_path = os.path.join(args.posterior_dir, POSTERIOR_FILE)
    run_sampler(
        cfg, log_posterior, data.eps, data.sigma_obs, data.svar, backend_path
    )
    print(f"Wrote {backend_path}")


if __name__ == "__main__":
    main()
